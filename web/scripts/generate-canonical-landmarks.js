/**
 * Generate canonical face landmarks from MediaPipe's official 3D face model
 *
 * Source: https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
 *
 * This script:
 * 1. Takes the first 468 vertices from the canonical face model (OBJ file)
 * 2. Normalizes them to a 0-1 bounding box for scale-independent testing
 * 3. Generates TypeScript fixture code for web/src/__tests__/fixtures/canonical-face.ts
 */

const fs = require('fs');
const path = require('path');

// First 468 vertices from canonical_face_model.obj
const rawLandmarks = JSON.parse(fs.readFileSync(path.join(__dirname, 'mediapipe-canonical-468.json'), 'utf8'));

// Find bounding box
let minX = Infinity, maxX = -Infinity;
let minY = Infinity, maxY = -Infinity;
let minZ = Infinity, maxZ = -Infinity;

for (const pt of rawLandmarks) {
  minX = Math.min(minX, pt.x);
  maxX = Math.max(maxX, pt.x);
  minY = Math.min(minY, pt.y);
  maxY = Math.max(maxY, pt.y);
  minZ = Math.min(minZ, pt.z);
  maxZ = Math.max(maxZ, pt.z);
}

const rangeX = maxX - minX;
const rangeY = maxY - minY;
const rangeZ = maxZ - minZ;

console.log('Bounding box:');
console.log(`  X: ${minX.toFixed(2)} to ${maxX.toFixed(2)} (range: ${rangeX.toFixed(2)})`);
console.log(`  Y: ${minY.toFixed(2)} to ${maxY.toFixed(2)} (range: ${rangeY.toFixed(2)})`);
console.log(`  Z: ${minZ.toFixed(2)} to ${maxZ.toFixed(2)} (range: ${rangeZ.toFixed(2)})`);

// Normalize to 0-1
const normalized = rawLandmarks.map(pt => ({
  x: (pt.x - minX) / rangeX,
  y: (pt.y - minY) / rangeY,
  z: (pt.z - minZ) / rangeZ,
}));

// Generate TypeScript code
const output = `import type { Point } from '@/lib/points';

/**
 * Canonical face landmark coordinates from MediaPipe's official 3D face model.
 *
 * Source: https://github.com/google-ai-edge/mediapipe/blob/master/mediapipe/modules/face_geometry/data/canonical_face_model.obj
 *
 * These are the first 468 vertices from the canonical_face_model.obj file, normalized to a 0-1 bounding box.
 * This provides authoritative reference geometry with correct facial proportions and landmark topology.
 *
 * Generated by: web/scripts/generate-canonical-landmarks.js
 * Do not edit manually - regenerate from source if needed.
 */
export function createCanonicalLandmarks(): Point[] {
  return [
${normalized.map((pt, i) => `    { x: ${pt.x.toFixed(6)}, y: ${pt.y.toFixed(6)}, z: ${pt.z.toFixed(6)} }, // ${i}`).join(',\n')}
  ];
}
`;

// Write output
const outputPath = path.join(__dirname, '..', 'src', '__tests__', 'fixtures', 'canonical-face.ts');
fs.writeFileSync(outputPath, output, 'utf8');

console.log(`\n✓ Generated ${outputPath}`);
console.log(`  ${normalized.length} landmarks normalized to [0, 1]³`);
